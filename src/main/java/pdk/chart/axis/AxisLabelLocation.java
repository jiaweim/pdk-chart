package pdk.chart.axis;

/**
 * Used to indicate the location of an axis label.
 */
public enum AxisLabelLocation {

    /**
     * Axis label at the top.
     */
    HIGH_END,

    /**
     * Axis label at the middle.
     */
    MIDDLE,

    /**
     * Axis label at the bottom.
     */
    LOW_END
}
