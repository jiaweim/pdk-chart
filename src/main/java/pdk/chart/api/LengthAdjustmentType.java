package pdk.chart.api;

/**
 * Represents the three options for adjusting a length:  expand, contract, and
 * no change.
 */
public enum LengthAdjustmentType {

    /**
     * NO_CHANGE.
     */
    NO_CHANGE,

    /**
     * EXPAND.
     */
    EXPAND,

    /**
     * CONTRACT.
     */
    CONTRACT

}
