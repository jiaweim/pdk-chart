package pdk.chart.api;

/**
 * An enumeration of the vertical alignment types ({@code TOP},
 * {@code BOTTOM} and {@code CENTER}).
 */
public enum VerticalAlignment {

    /**
     * Top alignment.
     */
    TOP,

    /**
     * Bottom alignment.
     */
    BOTTOM,

    /**
     * Center alignment.
     */
    CENTER

}

